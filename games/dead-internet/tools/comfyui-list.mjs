// Writes the ComfyUI production list from graphics/catalog.json (what the game needs) and
// graphics/comfyui.json (how each image is made: prompt, reference, derivation steps).
//   node games/dead-internet/tools/comfyui-list.mjs
// Output: graphics/COMFYUI.md (for people) and graphics/comfyui-jobs.json (for a batch script).
// Four groups: done, generate in ComfyUI, derive from another file (crop, mirror, logo → avatar),
// and make by hand (logos as vector art, documents with exact text, composites).

import { readFile, writeFile, access } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const GAME_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const cat = JSON.parse(await readFile(join(GAME_DIR, "graphics/catalog.json"), "utf8"));
const how = JSON.parse(await readFile(join(GAME_DIR, "graphics/comfyui.json"), "utf8"));
const exists = p => access(join(GAME_DIR, p)).then(() => true, () => false);

const STYLE = {
  photo: "realistic smartphone photo, natural light, slight sensor noise, no text overlays, no real brands",
  portrait: "realistic photo",
  profile: "square profile picture, realistic, as a person would choose for themselves",
  composite: "realistic photo",
  render: "",
  screenshot: "",
  scan: "",
};
const NEGATIVE = "watermark, signature, logo of a real brand, extra fingers, deformed hands, cartoon, illustration, 3d render, text artifacts, oversharpened";

/** SDXL-friendly generation size with the same aspect ratio as the final file. */
function genSize(w, h) {
  const r = w / h;
  const sizes = [[1024, 1024], [896, 1120], [832, 1216], [1216, 832], [1344, 768], [768, 1344], [1152, 896], [896, 1152]];
  return sizes.reduce((best, s) => Math.abs(s[0] / s[1] - r) < Math.abs(best[0] / best[1] - r) ? s : best);
}
/** A fixed seed per id, so a run can be repeated. */
const seed = id => { let x = 2166136261; for (const c of id) x = Math.imul(x ^ c.charCodeAt(0), 16777619) >>> 0; return x % 1e9; };

const byId = new Map(cat.images.map(i => [i.id, i]));
const groups = { done: [], generate: [], derive: [], manual: [], logo: [] };
const jobs = [];
for (const img of cat.images) {
  const m = how[img.id] || {};
  const final = img.status === "final" && await exists(img.file);
  const base = { id: img.id, file: img.file, width: img.width, height: img.height, usedIn: img.usedIn || [] };
  if (final) { groups.done.push({ ...base, note: m.notes || "" }); continue; }
  if (m.method === "derive" || img.derivedFrom) {
    const from = m.from || img.derivedFrom;
    groups.derive.push({ ...base, from, steps: m.steps || [img.transform], note: m.notes || "" });
    jobs.push({ id: img.id, method: "derive", from, steps: m.steps || [img.transform], out: img.file, width: img.width, height: img.height });
    continue;
  }
  if (m.method === "manual") {
    groups.manual.push({ ...base, how: m.how, prompt: m.prompt, note: m.notes || "" });
    continue;
  }
  if (img.kind === "logo" || !m.prompt) {
    groups.logo.push({ ...base, brief: img.brief });
    continue;
  }
  const [gw, gh] = genSize(img.width, img.height);
  const ref = m.faceRef || img.character;
  const refFile = ref ? cat.references?.[ref]?.file : null;
  const positive = [m.prompt, STYLE[img.kind]].filter(Boolean).join(", ");
  const job = { id: img.id, method: "generate", positive, negative: [NEGATIVE, m.negative].filter(Boolean).join(", "),
    genWidth: gw, genHeight: gh, width: img.width, height: img.height, seed: seed(img.id), out: img.file,
    ...(refFile ? { reference: refFile } : {}), ...(m.text ? { exactText: m.text } : {}),
    dependsOn: [...new Set([...(img.dependsOn || []), ...(m.dependsOn || [])])] };
  groups.generate.push({ ...base, job, note: m.notes || "", priority: img.priority });
  jobs.push(job);
}
// Generate originals before anything that depends on them.
const rank = id => (byId.get(id)?.priority === "optional" ? 1 : 0);
groups.generate.sort((a, b) => rank(a.id) - rank(b.id));

const md = [];
md.push(`# ComfyUI production list – Dead Internet

Generated by \`tools/comfyui-list.mjs\` from \`graphics/catalog.json\` and \`graphics/comfyui.json\`. Do not edit by hand.

**Status:** ${groups.done.length} done · ${groups.generate.length} to generate · ${groups.derive.length} to derive · ${groups.manual.length} by hand · ${groups.logo.length} logos

## How to use

1. Generate at the **generation size** (SDXL-friendly, same aspect ratio), upscale or downscale to the **final size**, and save as WebP under the **filename**.
2. Where a **reference** is given, use it: a face with IP-Adapter FaceID or InstantID, a place (the mill) with IP-Adapter or as an img2img start. References live in \`graphics/references/\`.
3. Where **exact text** is given, check the spelling; fix it in an editor if the model garbles it.
4. **Derived** images are never generated. They are made from the final original by the listed steps, so image search can match them.
5. When a file is in place: set \`status\` to \`final\` in \`graphics/catalog.json\`, and run \`node tools/comfyui-list.mjs\` and \`node tools/graphics-report.mjs\`.

Shared negative prompt: \`${NEGATIVE}\`

## Character references
${Object.entries(cat.references || {}).map(([k, r]) => `- **${k}** → \`${r.file}\` (from ${r.from}). ${r.note}`).join("\n")}
${Object.entries(cat.characters || {}).filter(([k]) => !cat.references?.[k]).map(([k, v]) => `- **${k}** (no reference yet): ${v}`).join("\n")}

## 1. Generate in ComfyUI (${groups.generate.length})
`);
for (const g of groups.generate) {
  const j = g.job;
  md.push(`### ${g.id}${g.priority === "optional" ? " (optional)" : ""}
- **File:** \`${g.file}\` · final ${g.width}×${g.height} · generate ${j.genWidth}×${j.genHeight} · seed ${j.seed}
- **Used in:** ${g.usedIn.join(", ") || "–"}${j.reference ? `\n- **Reference:** \`${j.reference}\`` : ""}${j.exactText ? `\n- **Exact text:** “${j.exactText}”` : ""}${j.dependsOn.length ? `\n- **Needs first:** ${j.dependsOn.join(", ")}` : ""}
- **Prompt:** ${j.positive}${how[g.id]?.negative ? `\n- **Extra negative:** ${how[g.id].negative}` : ""}${g.note ? `\n- **Note:** ${g.note}` : ""}
`);
}
md.push(`## 2. Derive from another file (${groups.derive.length})
Never generated: made from the final original with an editor or a script.
`);
for (const d of groups.derive) md.push(`### ${d.id} ← ${d.from}
- **File:** \`${d.file}\` · ${d.width}×${d.height} · used in ${d.usedIn.join(", ") || "–"}
${d.steps.map((s, i) => `${i + 1}. ${s}`).join("\n")}${d.note ? `\n- **Note:** ${d.note}` : ""}
`);
md.push(`## 3. Make by hand (${groups.manual.length})
`);
for (const m of groups.manual) md.push(`### ${m.id}
- **File:** \`${m.file}\` · ${m.width}×${m.height} · used in ${m.usedIn.join(", ") || "–"}
- **How:** ${m.how}${m.prompt ? `\n- **ComfyUI part:** ${m.prompt}` : ""}${m.note ? `\n- **Note:** ${m.note}` : ""}
`);
md.push(`## 4. Logos and icons (${groups.logo.length})
Vector art (SVG), drawn by hand or traced: models garble lettering. Original designs only.

| ID | File | Size | Brief |
|---|---|---|---|
${groups.logo.map(l => `| ${l.id} | \`${l.file}\` | ${l.width}×${l.height} | ${l.brief.replace(/\|/g, "/")} |`).join("\n")}

## Done (${groups.done.length})
${groups.done.map(d => `- **${d.id}** \`${d.file}\``).join("\n")}
`);

await writeFile(join(GAME_DIR, "graphics/COMFYUI.md"), md.join("\n"));
await writeFile(join(GAME_DIR, "graphics/comfyui-jobs.json"), JSON.stringify(jobs, null, 1) + "\n");
console.log(`COMFYUI.md: ${groups.done.length} done, ${groups.generate.length} generate, ${groups.derive.length} derive, ${groups.manual.length} manual, ${groups.logo.length} logos`);
